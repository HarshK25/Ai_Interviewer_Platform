import json
import re
import logging
import random
from datetime import datetime
from app.llm.llm_client import llm
from app.llm.prompt_templates import QUESTION_GENERATION_PROMPT, FOLLOWUP_PROMPT
from app.vector_store.chroma_client import chroma_client

logger = logging.getLogger(__name__)


class QuestionGenerator:

    async def generate_session_questions(
        self,
        session_id: str,
        user_id: str,
        job_role: str,
        job_description: str,
        num_questions: int = 5,
    ) -> list[dict]:
        """
        Every session gets FRESH, UNIQUE questions generated by LLM.
        The LLM uses:
          - Candidate's resume (from ChromaDB RAG)
          - Job role + description
          - Random seed/variation hint to ensure different questions every time
        """

        # 1. Retrieve candidate resume context from ChromaDB
        try:
            resume_results = chroma_client.query_resume(
                query=f"{job_role} skills experience projects",
                user_id=user_id,
                n_results=6,
            )
            resume_context = "\n\n".join(
                resume_results["documents"][0]
            ) if resume_results.get("documents") and resume_results["documents"][0] else "No resume data available"
        except Exception as e:
            logger.warning(f"Could not fetch resume context: {e}")
            resume_context = "No resume data available"

        # 2. Generate a variation hint to ensure different questions every session
        variation_hints = [
            "Focus more on system design and architecture decisions.",
            "Emphasize behavioral and teamwork scenarios.",
            "Prioritize problem-solving and debugging approaches.",
            "Focus on leadership, ownership, and project delivery.",
            "Emphasize hands-on coding and technical depth.",
            "Focus on communication, stakeholder management, and trade-offs.",
            "Prioritize scalability, performance, and optimization experience.",
            "Emphasize past failures, learnings, and growth mindset.",
        ]
        variation_hint = random.choice(variation_hints)
        timestamp_seed = datetime.now().strftime("%Y%m%d%H%M")

        # 3. Build prompt and invoke LLM
        prompt = QUESTION_GENERATION_PROMPT.format(
            resume_context=resume_context[:1500],  # reduced from 3000 to save tokens
            job_role=job_role,
            job_description=(job_description or job_role)[:300],  # reduced from 500
            num_questions=num_questions,
            variation_hint=variation_hint,
            session_seed=f"Session-{timestamp_seed}-{session_id[:8]}",
        )

        try:
            response = await llm.ainvoke(prompt)
            raw = response.content.strip()

            # Strip markdown code fences if present
            raw = re.sub(r"```(?:json)?\s*", "", raw).strip().rstrip("```").strip()

            # Extract JSON array
            json_match = re.search(r"\[.*\]", raw, re.DOTALL)
            if json_match:
                questions = json.loads(json_match.group())
                logger.info(
                    f"LLM generated {len(questions)} fresh questions for "
                    f"session {session_id} | role={job_role} | hint='{variation_hint}'"
                )
                return questions[:num_questions]
            else:
                logger.warning(f"LLM response was not a JSON array. Raw: {raw[:300]}")
                # Retry once with a simpler prompt
                return await self._retry_generation(job_role, job_description, resume_context, num_questions)

        except json.JSONDecodeError as e:
            logger.error(f"JSON parsing failed: {e}. Retrying...")
            return await self._retry_generation(job_role, job_description, resume_context, num_questions)

        except Exception as e:
            logger.error(f"Question generation failed: {e}. Retrying...", exc_info=True)
            return await self._retry_generation(job_role, job_description, resume_context, num_questions)

    async def _retry_generation(
        self,
        job_role: str,
        job_description: str,
        resume_context: str,
        num_questions: int,
    ) -> list[dict]:
        """
        Simpler retry prompt — used when the first attempt fails.
        Still LLM-generated, never fixed/hardcoded.
        """
        retry_prompt = f"""
You are a senior {job_role} interviewer. Generate exactly {num_questions} interview questions.

Candidate background:
{resume_context[:1500]}

Role: {job_role}
{"Description: " + job_description[:300] if job_description else ""}

Rules:
- Mix: behavioral, technical, and situational questions
- Make them specific to this candidate's background
- Each question should be answerable in 2-4 minutes verbally

Return ONLY a JSON array, no other text:
[
  {{
    "question_text": "Your question here",
    "question_type": "behavioral|technical|situational",
    "target_skills": ["skill1"],
    "difficulty": "easy|medium|hard"
  }}
]
"""
        try:
            response = await llm.ainvoke(retry_prompt)
            raw = response.content.strip()
            raw = re.sub(r"```(?:json)?\s*", "", raw).strip().rstrip("```").strip()
            json_match = re.search(r"\[.*\]", raw, re.DOTALL)
            if json_match:
                questions = json.loads(json_match.group())
                logger.info(f"Retry succeeded: generated {len(questions)} questions")
                return questions[:num_questions]
        except Exception as e:
            logger.error(f"Retry also failed: {e}")

        # Absolute last resort — generate with a super minimal prompt
        return await self._minimal_generation(job_role, num_questions)

    async def _minimal_generation(self, job_role: str, num_questions: int) -> list[dict]:
        """Last-resort single-line prompt — still LLM, still different every time."""
        try:
            prompt = (
                f"Generate {num_questions} different interview questions for a {job_role} candidate. "
                f"Return ONLY a JSON array with fields: question_text, question_type, target_skills, difficulty."
            )
            response = await llm.ainvoke(prompt)
            raw = re.sub(r"```(?:json)?\s*", "", response.content).strip().rstrip("```")
            json_match = re.search(r"\[.*\]", raw, re.DOTALL)
            if json_match:
                return json.loads(json_match.group())[:num_questions]
        except Exception as e:
            logger.error(f"Minimal generation failed too: {e}")

        # If ALL LLM attempts fail (no internet, invalid key, etc.) raise clearly
        raise RuntimeError(
            f"LLM question generation failed for role '{job_role}'. "
            "Please check your API key and LLM provider configuration."
        )

    async def generate_followup(
        self,
        original_question: str,
        candidate_answer: str,
        score_data: dict,
        job_role: str,
    ) -> str:
        """
        LLM generates a contextual follow-up question targeting weak score areas.
        Always fresh and specific to the candidate's actual answer.
        """
        weak_areas = [
            dim for dim in ["accuracy", "clarity", "depth", "relevance"]
            if score_data.get(f"{dim}_score", 10) < 6.0
        ]

        prompt = FOLLOWUP_PROMPT.format(
            job_role=job_role,
            original_question=original_question,
            candidate_answer=candidate_answer[:1000],
            weak_areas=", ".join(weak_areas) or "depth and specificity",
            overall_score=score_data.get("overall_score", 5.0),
        )
        try:
            response = await llm.ainvoke(prompt)
            return response.content.strip()
        except Exception as e:
            logger.error(f"Follow-up generation failed: {e}")
            # Even the fallback is LLM-generated but simpler
            try:
                simple = await llm.ainvoke(
                    f"Ask one probing follow-up question about: '{original_question}' "
                    f"for a {job_role} candidate. Return only the question."
                )
                return simple.content.strip()
            except Exception:
                return (
                    "Can you walk me through a specific example from your experience "
                    "that demonstrates this skill in more detail?"
                )


question_generator = QuestionGenerator()
